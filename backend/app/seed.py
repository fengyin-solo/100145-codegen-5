"""示例数据：每个模块给几条不同状态的记录，方便起服务后立刻看到内容。"""
from __future__ import annotations

from typing import Any


def _emergency_seed_row(
    row_id: int,
    *,
    code: str,
    kind: str,
    location: str,
    impact: str,
    crew: str,
    reporter: str,
    reported_at: Any,
    status: str,
    sla_hours: int,
    stage_times: dict[str, Any],
) -> dict[str, Any]:
    """组装一条突发事件样例；stage_times 给出各处置阶段的发生时间，
    据此回溯完整处置经过，保证看板与详情看到的是同一份状态。
    """
    stage_notes = {
        "待处置": "应急中心接报登记，等待班组出动",
        "处置中": "班组到达现场，设置围挡并开展处置",
        "已控制": "险情已控制，现场转入清理收尾",
        "已恢复": "路面清理验收完毕，道路恢复正常通行",
    }
    timeline = [
        {
            "stage": stage,
            "time": stage_times[stage],
            "crew": crew if stage != "待处置" else "应急中心",
            "note": stage_notes[stage],
        }
        for stage in ("待处置", "处置中", "已控制", "已恢复")
        if stage in stage_times
    ]
    return {
        "id": row_id,
        "status": status,
        "pending": status != "已恢复",
        "abnormal": False,
        "事件编号": code,
        "事件类型": kind,
        "发生位置": location,
        "影响范围": impact,
        "处置班组": crew,
        "上报时间": reported_at,
        "上报人员": reporter,
        "处置时限": f"{sla_hours}小时",
        "timeline": timeline,
    }


